"""Pair guidellm's per-request output tokens with vLLM's real completion_tokens.

    python compare.py <work_dir> <runs>

Reads <work_dir>/{main,pr}_<i>.json, .proxy.jsonl and .log from run.sh and writes
results/compare.md, results/main.json and results/pr.json (run 1), and per-run
copies under results/runs/.

Pairing: successful guidellm requests sorted by request_start_time are matched to
proxy log lines in order (the profile is synchronous, one request at a time).
Each pair is then checked by exact equality of the response text.
"""

import json
import os
import shutil
import statistics
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")
RUNS_DIR = os.path.join(RES, "runs")
LIMIT = 10 * 1024 * 1024
WARNING = "The server returned no token usage"


def load(work, v, i):
    with open(f"{work}/{v}_{i}.json") as f:
        bench = json.load(f)["benchmarks"][0]
    with open(f"{work}/{v}_{i}.proxy.jsonl", encoding="utf-8") as f:
        proxy = [json.loads(line) for line in f]
    with open(f"{work}/{v}_{i}.log", encoding="utf-8", errors="replace") as f:
        log = f.read()
    return bench, proxy, log


def analyze(bench, proxy, log):
    req = bench["requests"]
    ok = sorted(req["successful"], key=lambda r: r["request_start_time"])
    rows = []
    for n, (g, p) in enumerate(zip(ok, proxy), 1):
        rows.append({
            "n": n,
            "actual": p["completion_tokens"],
            "guidellm": g["output_metrics"]["text_tokens"],
            "finish": p["finish_reason"],
            "text_match": g["output"] == p["text"],
            "latency_s": g["request_latency"],
        })
    actual = sum(r["actual"] for r in rows)
    reported = sum(r["guidellm"] for r in rows)
    latency = sum(r["latency_s"] for r in rows)
    m = bench["metrics"]
    return {
        "rows": rows,
        "successful": len(ok),
        "errored": len(req["errored"]),
        "incomplete": len(req["incomplete"]),
        "errors": sorted({str(r.get("info", {}).get("error")) for r in req["errored"]}),
        "proxy_lines": len(proxy),
        "pairs_text_match": sum(r["text_match"] for r in rows),
        "actual_total": actual,
        "guidellm_total": reported,
        "diff_total": reported - actual,
        "requests_differ": sum(r["actual"] != r["guidellm"] for r in rows),
        "eos_stops": sum(r["finish"] == "stop" for r in rows),
        "tok_s_guidellm": m["output_tokens_per_second"]["successful"]["mean"],
        "tpot_ms_guidellm": m["time_per_output_token_ms"]["successful"]["mean"],
        "tok_s_from_tokens_actual": actual / latency,
        "tok_s_from_tokens_guidellm": reported / latency,
        "tpot_ms_actual": latency / actual * 1000,
        "tpot_ms_from_tokens_guidellm": latency / reported * 1000,
        "warning_count": log.count(WARNING),
        "prompts": [json.dumps(json.loads(r["request_args"])["body"].get("messages"), sort_keys=True)
                    for r in ok],
    }


def copy_json(src, dst):
    if os.path.getsize(src) <= LIMIT:
        shutil.copy(src, dst)
        return
    raise SystemExit(f"{src} is over 10MB; add a field-only summary before committing")


def med(items, key):
    return statistics.median(x[key] for x in items)


def fmt(x):
    return f"{x:.2f}"


def main():
    work, runs = sys.argv[1], int(sys.argv[2])
    os.makedirs(RUNS_DIR, exist_ok=True)
    data = {}
    for v in ("main", "pr"):
        data[v] = []
        for i in range(1, runs + 1):
            data[v].append(analyze(*load(work, v, i)))
            copy_json(f"{work}/{v}_{i}.json", f"{RUNS_DIR}/{v}_{i}.json")
            shutil.copy(f"{work}/{v}_{i}.proxy.jsonl", RUNS_DIR)
            shutil.copy(f"{work}/{v}_{i}.log", RUNS_DIR)
        os.replace(f"{RUNS_DIR}/{v}_1.json", f"{RES}/{v}.json")
    shutil.copy(f"{work}/env.txt", RES)

    out = ["# guidellm #1546 check: real completion_tokens vs guidellm text_tokens", ""]
    out += ["Generated by `compare.py`. `main.json` and `pr.json` are run 1; runs 2-5 are in "
            "`runs/`.", ""]
    out += ["Pairing: successful requests sorted by `request_start_time`, matched in order to "
            "proxy log lines, then checked by exact response text equality.", ""]
    out += ["`tok/s (reported)` and `TPOT (reported)` are guidellm's "
            "`output_tokens_per_second` and `time_per_output_token_ms` successful means. "
            "`tok/s (real)` is real tokens / summed request latency; `TPOT (real)` is the "
            "inverse in ms.", ""]
    out += ["## Per run", ""]
    out += ["| variant | run | ok | errored | proxy lines | text matches | EOS stops | real total "
            "| guidellm total | diff | requests differ | tok/s (reported) | tok/s (real) "
            "| TPOT ms (reported) | TPOT ms (real) | warning count |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for v in ("main", "pr"):
        for i, a in enumerate(data[v], 1):
            out.append(
                f"| {v} | {i} | {a['successful']} | {a['errored']} | {a['proxy_lines']} "
                f"| {a['pairs_text_match']} | {a['eos_stops']} | {a['actual_total']} "
                f"| {a['guidellm_total']} | {a['diff_total']:+d} | {a['requests_differ']} "
                f"| {fmt(a['tok_s_guidellm'])} | {fmt(a['tok_s_from_tokens_actual'])} "
                f"| {fmt(a['tpot_ms_guidellm'])} | {fmt(a['tpot_ms_actual'])} "
                f"| {a['warning_count']} |")
    out += ["", "## Medians over runs", "",
            "| variant | real total | guidellm total | diff | diff % of real | tok/s (reported) "
            "| tok/s (real) | TPOT ms (reported) | TPOT ms (real) |",
            "|---|---|---|---|---|---|---|---|---|"]
    for v in ("main", "pr"):
        a = data[v]
        pct = statistics.median(x["diff_total"] / x["actual_total"] * 100 for x in a)
        out.append(f"| {v} | {med(a, 'actual_total')} | {med(a, 'guidellm_total')} "
                   f"| {med(a, 'diff_total'):+g} | {pct:+.2f}% | {fmt(med(a, 'tok_s_guidellm'))} "
                   f"| {fmt(med(a, 'tok_s_from_tokens_actual'))} "
                   f"| {fmt(med(a, 'tpot_ms_guidellm'))} | {fmt(med(a, 'tpot_ms_actual'))} |")

    out += ["", "## Per-request difference distribution (guidellm - real, all runs)", "",
            "| variant | finish_reason | diff | requests |", "|---|---|---|---|"]
    for v in ("main", "pr"):
        counts = {}
        for a in data[v]:
            for r in a["rows"]:
                k = (r["finish"], r["guidellm"] - r["actual"])
                counts[k] = counts.get(k, 0) + 1
        for (fin, d), c in sorted(counts.items(), key=lambda kv: (str(kv[0][0]), kv[0][1])):
            out.append(f"| {v} | {fin} | {d:+d} | {c} |")

    out += ["", "## Errored requests", ""]
    for v in ("main", "pr"):
        msgs = sorted({e for a in data[v] for e in a["errors"]})
        out.append(f"- {v}: {[a['errored'] for a in data[v]]} per run. Messages: {msgs}")

    same = all(data["main"][i]["prompts"] == data["pr"][i]["prompts"] for i in range(runs))
    across = all(a["prompts"] == data["main"][0]["prompts"] for v in data for a in data[v])
    out += ["", f"Prompts identical between main and pr within each run index: {same}.",
            f"Prompts identical across all runs: {across}.", ""]

    for v in ("main", "pr"):
        out += [f"## Per request, {v}", ""]
        for i, a in enumerate(data[v], 1):
            out += [f"### Run {i}", "", "| # | real | guidellm | diff | finish | text match |",
                    "|---|---|---|---|---|---|"]
            out += [f"| {r['n']} | {r['actual']} | {r['guidellm']} "
                    f"| {r['guidellm'] - r['actual']:+d} | {r['finish']} | {r['text_match']} |"
                    for r in a["rows"]]
            out.append("")

    with open(f"{RES}/compare.md", "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("\n".join(out[: out.index("## Per request, main")]))


if __name__ == "__main__":
    main()
